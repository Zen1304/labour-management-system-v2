import { desc, eq, sql } from 'drizzle-orm';
import Link from 'next/link';
import { requireCapability } from '@/lib/auth/guard';
import { authCsrfToken } from '@/lib/auth/action-helpers';
import { can } from '@/lib/auth/permissions';
import { db } from '@/lib/db/client';
import { payrollRuns, payrollItems, users } from '@/lib/db/schema';
import { AppShell } from '@/components/app-shell';
import { Button } from '@/components/ui/button';
import { flagRunAction } from './actions';

export const instant = false;

const STATUS_LABEL: Record<string, string> = {
  pending_verification: 'Pending verification',
  verified: 'Verified',
  completed: 'Completed',
};

export default async function PayrollListPage() {
  const user = await requireCapability('payroll.view');
  const csrf = await authCsrfToken();
  const canGenerate = can(user, 'payroll.generate');

  const runs = await db
    .select({
      id: payrollRuns.id,
      periodStart: payrollRuns.periodStart,
      periodEnd: payrollRuns.periodEnd,
      status: payrollRuns.status,
      flagged: payrollRuns.flagged,
      generatedAt: payrollRuns.generatedAt,
      generatedByName: users.name,
      netTotal: sql<number>`coalesce((select sum(${payrollItems.basePay} + ${payrollItems.overtimePay}) from ${payrollItems} where ${payrollItems.payrollRunId} = ${payrollRuns.id}), 0)`,
    })
    .from(payrollRuns)
    .leftJoin(users, eq(payrollRuns.generatedBy, users.id))
    .orderBy(desc(payrollRuns.id));

  return (
    <AppShell user={user}>
      <div className="mb-2 flex items-center justify-between">
        <h1 className="text-2xl font-bold">Payroll</h1>
        {canGenerate && (
          <Link href="/payroll/new">
            <Button>+ Generate payroll run</Button>
          </Link>
        )}
      </div>
      <p className="mb-6 text-sm text-neutral-500">
        Pay periods run Thursday → Wednesday. Generated by Labor Manager, then Verified and Completed by Audit Manager,
        site by site, across all three pay modes. A period can only be generated once — flag a run first if it needs to
        be redone.
      </p>

      <table className="w-full border-collapse text-sm">
        <thead>
          <tr className="border-b border-neutral-200 text-left text-neutral-500">
            <th className="py-2">Period</th>
            <th className="py-2">Status</th>
            <th className="py-2">Generated by</th>
            <th className="py-2">Net total</th>
            <th className="py-2"></th>
            <th className="py-2"></th>
          </tr>
        </thead>
        <tbody>
          {runs.map((r) => (
            <tr key={r.id} className={`border-b border-neutral-100 ${r.flagged ? 'opacity-60' : ''}`}>
              <td className="py-2">
                {r.periodStart} → {r.periodEnd}
              </td>
              <td className="py-2">
                {STATUS_LABEL[r.status] || r.status}
                {r.flagged ? ' · Flagged' : ''}
              </td>
              <td className="py-2">{r.generatedByName || '—'}</td>
              <td className="py-2">₹{Number(r.netTotal).toFixed(2)}</td>
              <td className="py-2">
                <Link href={`/payroll/${r.id}`} className="text-blue-600 hover:underline">
                  View
                </Link>
              </td>
              <td className="py-2">
                {canGenerate && !r.flagged && (
                  <form action={flagRunAction}>
                    <input type="hidden" name="_csrf" value={csrf} />
                    <input type="hidden" name="runId" value={r.id} />
                    <Button type="submit" variant="outline">
                      Flag
                    </Button>
                  </form>
                )}
              </td>
            </tr>
          ))}
          {runs.length === 0 && (
            <tr>
              <td colSpan={6} className="py-4 text-center text-neutral-400">
                No payroll runs yet.
              </td>
            </tr>
          )}
        </tbody>
      </table>
    </AppShell>
  );
}
